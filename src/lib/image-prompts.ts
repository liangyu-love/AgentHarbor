export type PromptRecipe = {
  /** Short display title for the recipe card. */
  title: string;
  /** One-line pitfall / usage note shown under the title. */
  tip: string;
  /** Ready-to-paste prompt body. */
  prompt: string;
  /** Stable id for favorites and list keys. */
  id?: string;
};

export type PromptLibraryCategory = {
  category: string;
  /** Optional style accent used by the recipe cards. */
  tone: "ink" | "gold" | "indigo" | "jade" | "rose";
  recipes: PromptRecipe[];
};

/** Stable key for favorites storage. */
export const promptRecipeKey = (category: string, recipe: PromptRecipe) =>
  recipe.id ?? `${category}::${recipe.title}`;

/** Assign stable ids once so favorites survive title tweaks. */
function withStablePromptIds(library: PromptLibraryCategory[]): PromptLibraryCategory[] {
  return library.map(cat => ({
    ...cat,
    recipes: cat.recipes.map((recipe, index) => ({
      ...recipe,
      id: recipe.id ?? `${cat.category}#${index + 1}`,
    })),
  }));
}

const FAVORITES_STORAGE_KEY = "image-prompt-favorites";

export function loadPromptFavorites(): string[] {
  try {
    const raw = localStorage.getItem(FAVORITES_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    return Array.isArray(parsed) ? parsed.filter((item): item is string => typeof item === "string") : [];
  } catch {
    return [];
  }
}

export function savePromptFavorites(keys: string[]) {
  try {
    localStorage.setItem(FAVORITES_STORAGE_KEY, JSON.stringify(keys));
  } catch {
    // Storage may be unavailable; favorites then last for this session only.
  }
}

export function togglePromptFavorite(keys: string[], key: string) {
  return keys.includes(key) ? keys.filter(item => item !== key) : [...keys, key];
}

